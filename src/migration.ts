import type {State} from './snapshot.ts';

/** Drizzle's migrator splits a migration file into statements on this line. */
export const statementBreakpoint = '--> statement-breakpoint';
const stateMarker = '-- drizzle-triggers:state ';

/**
 * The contents of a migration file: the statements, then the state as a comment line.
 * The state goes on the last statement rather than its own, so no statement is only a comment.
 */
export function renderMigration(statements: readonly string[], state: State): string {
	const header = '-- Generated by drizzle-triggers from your pgFunction() and pgTrigger() definitions.';
	return `${header}\n${statements.join(`\n${statementBreakpoint}\n`)}\n${stateMarker}${JSON.stringify(state)}\n`;
}

function isState(value: unknown): value is State {
	const candidate = value as State | null;
	return typeof candidate === 'object' && candidate !== null && candidate.version === 1
		&& typeof candidate.functions === 'object' && candidate.functions !== null
		&& typeof candidate.triggers === 'object' && candidate.triggers !== null;
}

/** The text after the last state marker that starts a line, without scanning or splitting the whole file. */
function stateText(migration: string): string | undefined {
	const index = migration.startsWith(stateMarker) ? 0 : -1;
	const lineIndex = migration.lastIndexOf(`\n${stateMarker}`);
	const start = lineIndex === -1 ? index : lineIndex + 1;
	if (start === -1) {
		return undefined;
	}

	const end = migration.indexOf('\n', start);
	return migration.slice(start + stateMarker.length, end === -1 ? undefined : end).trimEnd();
}

/** The state saved in a migration file, or `undefined` when it has none. */
export function readState(migration: string): State | undefined {
	const text = stateText(migration);
	if (text === undefined) {
		return undefined;
	}

	let state: unknown;
	try {
		state = JSON.parse(text);
	} catch {
		state = undefined;
	}

	if (!isState(state)) {
		throw new Error(`Unsupported drizzle-triggers state, was the migration edited by hand? ${text.slice(0, 200)}`);
	}

	return state;
}

/**
 * The state from the newest migration that has one. Pass the migrations newest first, lazily if you like:
 * only the files up to the first one with a state are read.
 */
export function latestState(migrationsNewestFirst: Iterable<string>): State | undefined {
	for (const migration of migrationsNewestFirst) {
		const state = readState(migration);
		if (state !== undefined) {
			return state;
		}
	}

	return undefined;
}
