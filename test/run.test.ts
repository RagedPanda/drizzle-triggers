import assert from 'node:assert/strict';
import {existsSync, mkdirSync, readFileSync, writeFileSync} from 'node:fs';
import path from 'node:path';
import {test, type TestContext} from 'node:test';
import {runCli, usage, type CliEnvironment} from '../src/cli/run.ts';
import {pgFunction, pgTrigger} from '../src/definitions.ts';
import {readState} from '../src/migration.ts';
import {users} from './fixtures.ts';
import {temporaryProject} from './helpers.ts';

const touch = pgFunction('touch', {returns: 'trigger', body: 'BEGIN RETURN NEW; END;'});
const usersTouch = pgTrigger('users_touch', {table: users, timing: 'before', events: ['update'], function: touch});

type FakeOptions = {
	readonly config?: unknown;
	readonly schema?: Record<string, unknown>;
	/** Folder names drizzle-kit creates, one per call. */
	readonly createdFolders?: string[];
	readonly drizzleKitStatus?: number;
};

function fakeEnvironment(t: TestContext, options: FakeOptions = {}) {
	const cwd = temporaryProject(t, {'drizzle.config.ts': '', 'schema.ts': ''});
	const output: string[] = [];
	const errors: string[] = [];
	const drizzleKitCalls: (readonly string[])[] = [];
	const sleeps: number[] = [];
	const createdFolders = [...(options.createdFolders ?? ['20261030120000_triggers', '20261030120001_triggers'])];
	const environment: CliEnvironment = {
		cwd,
		print: text => output.push(text),
		printError: text => errors.push(text),
		importModule: async file => (file.endsWith('drizzle.config.ts')
			? options.config ?? {default: {dialect: 'postgresql', schema: './schema.ts'}}
			: options.schema ?? {touch, usersTouch}),
		runDrizzleKit(args) {
			drizzleKitCalls.push(args);
			const folder = path.join(cwd, 'drizzle', createdFolders.shift()!);
			mkdirSync(folder, {recursive: true});
			writeFileSync(path.join(folder, 'migration.sql'), '-- Custom SQL migration file, put your code below! --\n');
			return options.drizzleKitStatus ?? 0;
		},
		sleep: async milliseconds => {
			sleeps.push(milliseconds);
		},
	};
	return {cwd, environment, output, errors, drizzleKitCalls, sleeps};
}

test('runCli prints the usage for --help, and fails without a command', async t => {
	const {environment, output} = fakeEnvironment(t);
	assert.equal(await runCli(['--help'], environment), 0);
	assert.equal(await runCli(['generate', '-h'], environment), 0);
	assert.equal(await runCli([], environment), 1);
	assert.deepEqual(output, [usage, usage, usage]);
});

test('runCli rejects unknown commands and options', async t => {
	const {environment, errors} = fakeEnvironment(t);
	assert.equal(await runCli(['push'], environment), 1);
	assert.match(errors[0]!, /^Unknown command push\n\nUsage:/);
	assert.equal(await runCli(['generate', '--force'], environment), 1);
	assert.match(errors[1]!, /^drizzle-triggers: Unknown option '--force'/);
});

test('generate writes the migration into the file drizzle-kit creates', async t => {
	const {cwd, environment, output, drizzleKitCalls} = fakeEnvironment(t);
	assert.equal(await runCli(['generate', '--name', 'touch'], environment), 0);
	assert.deepEqual(drizzleKitCalls, [['generate', '--custom', '--name=touch', `--config=${path.join(cwd, 'drizzle.config.ts')}`]]);
	const migration = readFileSync(path.join(cwd, 'drizzle/20261030120000_triggers/migration.sql'), 'utf8');
	assert.match(migration, /^-- Generated by drizzle-triggers/);
	assert.match(migration, /CREATE OR REPLACE FUNCTION "touch"\(\)[\s\S]+--> statement-breakpoint\nCREATE TRIGGER "users_touch"/);
	assert.deepEqual(Object.keys(readState(migration)!.triggers), ['public.users.users_touch']);
	assert.deepEqual(output, ['Wrote 2 statements to drizzle/20261030120000_triggers/migration.sql']);

	assert.equal(await runCli(['generate'], environment), 0);
	assert.equal(drizzleKitCalls.length, 1);
	assert.equal(output[1], 'No function or trigger changes, nothing to generate.');
});

test('generate tries again when the new migration would not run last', async t => {
	const {cwd, environment, sleeps, drizzleKitCalls} = fakeEnvironment(t, {createdFolders: ['20261030115959_aaa', '20261030120001_triggers']});
	mkdirSync(path.join(cwd, 'drizzle/20261030115959_init'), {recursive: true});
	writeFileSync(path.join(cwd, 'drizzle/20261030115959_init/migration.sql'), 'CREATE TABLE "users" ();');
	assert.equal(await runCli(['generate'], environment), 0);
	assert.equal(drizzleKitCalls.length, 2);
	assert.deepEqual(sleeps, [1000]);
	assert.ok(!existsSync(path.join(cwd, 'drizzle/20261030115959_aaa')));
	assert.match(readFileSync(path.join(cwd, 'drizzle/20261030120001_triggers/migration.sql'), 'utf8'), /drizzle-triggers:state/);
});

test('generate gives up when the new migration keeps sorting first', async t => {
	const {cwd, environment, errors} = fakeEnvironment(t, {createdFolders: ['1_a', '1_b', '1_c']});
	mkdirSync(path.join(cwd, 'drizzle/2_init'), {recursive: true});
	writeFileSync(path.join(cwd, 'drizzle/2_init/migration.sql'), '');
	assert.equal(await runCli(['generate'], environment), 1);
	assert.deepEqual(errors, ['Could not create a migration that sorts after the existing ones in 3 attempts']);
});

test('generate reports a failing drizzle-kit and an unexpected number of new files', async t => {
	const failing = fakeEnvironment(t, {drizzleKitStatus: 2});
	assert.equal(await runCli(['generate'], failing.environment), 2);
	assert.deepEqual(failing.errors, ['drizzle-kit generate --custom failed with exit code 2']);

	const silent = fakeEnvironment(t);
	const environment = {...silent.environment, runDrizzleKit: () => 0};
	assert.equal(await runCli(['generate'], environment), 1);
	assert.deepEqual(silent.errors, ['drizzle-triggers: Expected drizzle-kit to create one migration, found 0']);
});

test('check passes when the migrations are up to date and fails otherwise', async t => {
	const {environment, output, errors} = fakeEnvironment(t);
	assert.equal(await runCli(['check'], environment), 1);
	assert.match(errors[0]!, /^Functions or triggers changed without a migration. Run drizzle-triggers generate. Pending:\n\nCREATE OR REPLACE FUNCTION "touch"/);
	await runCli(['generate'], environment);
	assert.equal(await runCli(['check', '--config', 'drizzle.config.ts'], environment), 0);
	assert.equal(output.at(-1), 'Functions and triggers match the migrations.');
});

test('sql prints statements that can run on any database', async t => {
	const {environment, output} = fakeEnvironment(t, {config: {default: {dialect: 'postgresql', schema: 'schema.ts', casing: 'snake_case'}}});
	assert.equal(await runCli(['sql'], environment), 0);
	assert.match(output[0]!, /^DROP TRIGGER IF EXISTS "users_touch" ON "users";\n\nCREATE OR REPLACE FUNCTION "touch"\(\)[\s\S]+\n\nCREATE TRIGGER "users_touch"/);
});

test('runCli reports configuration errors', async t => {
	const noSchema = fakeEnvironment(t, {config: {default: {dialect: 'postgresql', schema: './src/*.ts'}}});
	assert.equal(await runCli(['sql'], noSchema.environment), 1);
	assert.deepEqual(noSchema.errors, ['drizzle-triggers: No schema files match ./src/*.ts']);

	const noConfig = fakeEnvironment(t);
	assert.equal(await runCli(['sql', '-c', 'other.ts'], noConfig.environment), 1);
	assert.match(noConfig.errors[0]!, /^drizzle-triggers: No drizzle config found: looked for other.ts in /);
});

test('runCli reports a schema file that throws something other than an Error', async t => {
	const {environment, errors} = fakeEnvironment(t);
	const failing: CliEnvironment = {...environment, importModule: async file => {
		if (file.endsWith('schema.ts')) {
			throw 'schema.ts: unexpected token';
		}

		return environment.importModule(file);
	}};
	assert.equal(await runCli(['sql'], failing), 1);
	assert.deepEqual(errors, ['drizzle-triggers: schema.ts: unexpected token']);
});

test('generate says "statement" for a single one', async t => {
	const {environment, output} = fakeEnvironment(t, {schema: {touch}});
	assert.equal(await runCli(['generate'], environment), 0);
	assert.deepEqual(output, ['Wrote 1 statement to drizzle/20261030120000_triggers/migration.sql']);
});
