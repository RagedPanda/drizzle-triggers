import assert from 'node:assert/strict';
import {readFileSync, rmSync, writeFileSync} from 'node:fs';
import path from 'node:path';
import {test} from 'node:test';
import {PGlite} from '@electric-sql/pglite';
import {sql} from 'drizzle-orm';
import {drizzle} from 'drizzle-orm/pglite';
import {migrate} from 'drizzle-orm/pglite/migrator';
import {casingInTableBuilders} from '../../src/columns.ts';
import {nodeEnvironment} from '../../src/cli/environment.ts';
import {runCli} from '../../src/cli/run.ts';
import {migrationFiles} from '../../src/cli/project.ts';
import {sourceIndex, temporaryProject} from '../helpers.ts';

/** Drizzle wraps database errors in a "Failed query" error; the trigger's message is on its cause. */
function rejection(message: RegExp) {
	return (error: Error & {cause?: Error}) => message.test(error.cause?.message ?? error.message);
}

const config = `import {defineConfig} from 'drizzle-kit';
export default defineConfig({dialect: 'postgresql', schema: './db', out: './drizzle', casing: 'snake_case'});
`;

// Drizzle 1.0 ignores the config's casing and snake-cases in the table builder instead.
const tableBuilder = casingInTableBuilders ? {name: 'snakeCase', call: 'snakeCase.table'} : {name: 'pgTable', call: 'pgTable'};

// An extensionless import, which Node.js itself would not resolve, like many real schema folders have.
const tables = `import {${tableBuilder.name}, serial, text} from 'drizzle-orm/pg-core';
import {timestamps} from './columns';
export const users = ${tableBuilder.call}('users', {id: serial().primaryKey(), name: text().notNull(), status: text().notNull().default('new'), ...timestamps});
`;

const columns = `import {timestamp} from 'drizzle-orm/pg-core';
export const timestamps = {updatedAt: timestamp().defaultNow().notNull()};
`;

function triggers(condition: string): string {
	return `import {sql} from 'drizzle-orm';
import {pgFunction, pgTrigger, updatedAtTrigger} from ${JSON.stringify(sourceIndex)};
import {users} from './tables';
export const usersUpdatedAt = updatedAtTrigger(users, users.updatedAt);
export const rejectStatus = pgTrigger('users_reject_status', {
	table: users,
	timing: 'before',
	events: ['insert', 'update'],
	when: ({NEW}) => sql\`\${NEW.status} = ${condition}\`,
	function: pgFunction('reject', {returns: 'trigger', body: "BEGIN RAISE EXCEPTION 'rejected %', NEW.status; END;"}),
});
`;
}

test('generate, check and migrate a real project with drizzle-kit', {timeout: 120_000}, async t => {
	const cwd = temporaryProject(t, {
		'drizzle.config.ts': config,
		// A project's own tsconfig, so drizzle-kit does not pick up the target of this repository's.
		'tsconfig.json': JSON.stringify({compilerOptions: {target: 'es2022', module: 'esnext', moduleResolution: 'bundler'}}),
		'db/tables.ts': tables,
		'db/columns.ts': columns,
		'db/triggers.ts': triggers('\'banned\''),
	});
	const output: string[] = [];
	const environment = {...nodeEnvironment(cwd), print: (text: string) => output.push(text), printError: (text: string) => output.push(text)};
	const outFolder = path.join(cwd, 'drizzle');

	assert.equal(environment.runDrizzleKit(['generate', '--config=drizzle.config.ts']), 0);
	assert.equal(await runCli(['check'], environment), 1);
	assert.equal(await runCli(['generate'], environment), 0);
	assert.equal(await runCli(['check'], environment), 0);

	// Our exports must not confuse drizzle-kit: it sees no schema changes.
	assert.equal(environment.runDrizzleKit(['generate', '--config=drizzle.config.ts']), 0);
	assert.equal(migrationFiles(outFolder).length, 2);
	assert.match(readFileSync(migrationFiles(outFolder)[1]!, 'utf8'), /CREATE TRIGGER "users_set_updated_at"/);

	const client = new PGlite();
	t.after(() => client.close());
	const db = drizzle({client, casing: 'snake_case'});
	await migrate(db, {migrationsFolder: outFolder});
	await db.execute(sql`INSERT INTO users (name, updated_at) VALUES ('ada', '2000-01-01')`);
	await db.execute(sql`UPDATE users SET name = 'grace'`);
	const updated = await db.execute<{year: number}>(sql`SELECT extract(year FROM updated_at)::int AS year FROM users`);
	assert.ok(updated.rows[0]!.year > 2000);
	await assert.rejects(db.execute(sql`UPDATE users SET status = 'banned'`), rejection(/rejected banned/));

	// Change the trigger condition: a new migration drops and recreates only that trigger.
	// A new file, because jiti caches modules for the life of the process, which is one run of the real CLI.
	rmSync(path.join(cwd, 'db/triggers.ts'));
	writeFileSync(path.join(cwd, 'db/rules.ts'), triggers('\'blocked\''));
	assert.equal(await runCli(['check'], environment), 1);
	assert.equal(await runCli(['generate', '--name=block'], environment), 0);
	const third = readFileSync(migrationFiles(outFolder)[2]!, 'utf8');
	assert.match(third, /^-- Generated by drizzle-triggers[^\n]*\nDROP TRIGGER IF EXISTS "users_reject_status" ON "users";\n--> statement-breakpoint\nCREATE TRIGGER "users_reject_status"/);
	await migrate(db, {migrationsFolder: outFolder});
	await db.execute(sql`UPDATE users SET status = 'banned'`);
	await assert.rejects(db.execute(sql`UPDATE users SET status = 'blocked'`), rejection(/rejected blocked/));
	assert.match(output.join('\n'), /Wrote 4 statements to drizzle[\\/].*triggers[^\n]*\n[\s\S]*Wrote 2 statements to drizzle[\\/].*block/);
});
